CREATE TABLE scheduled_task_log (
    id uuid PRIMARY KEY,
    task_name varchar(100) NOT NULL,
    status varchar(20) NOT NULL,
    trigger_type varchar(20) NOT NULL,
    instance_id varchar(100),
    started_at timestamp with time zone NOT NULL,
    finished_at timestamp with time zone,
    duration_ms bigint,
    processed_count integer NOT NULL DEFAULT 0,
    success_count integer NOT NULL DEFAULT 0,
    failure_count integer NOT NULL DEFAULT 0,
    error_type varchar(200),
    error_message varchar(500)
);
CREATE INDEX idx_scheduled_task_log_task_time ON scheduled_task_log(task_name, started_at DESC);
CREATE INDEX idx_scheduled_task_log_status_time ON scheduled_task_log(status, started_at DESC);

CREATE TABLE scheduled_task_event_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_log_id uuid NOT NULL REFERENCES scheduled_task_log(id),
    event_id uuid NOT NULL,
    routing_key varchar(80) NOT NULL,
    origin_user_id bigint,
    origin_chat_id bigint,
    origin_message_id bigint,
    origin_client_message_id uuid,
    origin_operation varchar(40),
    origin_source varchar(100),
    attempt_number integer NOT NULL,
    status varchar(20) NOT NULL,
    duration_ms bigint NOT NULL,
    error_type varchar(200),
    error_message varchar(500)
);
CREATE INDEX idx_scheduled_task_event_log_event ON scheduled_task_event_log(event_id);
CREATE INDEX idx_scheduled_task_event_log_user ON scheduled_task_event_log(origin_user_id, id DESC);
CREATE INDEX idx_scheduled_task_event_log_client_id ON scheduled_task_event_log(origin_client_message_id);
