CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255),
    username varchar(255),
    email varchar(255),
    password varchar(255),
    phone_number varchar(255),
    location varchar(255),
    biography text,
    profile_complete boolean NOT NULL DEFAULT false,
    created_at timestamp(6),
    updated_at timestamp(6)
);

CREATE TABLE music_genre (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL UNIQUE
);

CREATE TABLE user_genre (
    user_id bigint NOT NULL REFERENCES users(id),
    genre_id bigint NOT NULL REFERENCES music_genre(id),
    PRIMARY KEY (user_id, genre_id)
);

CREATE TABLE user_social_networks (
    user_id bigint NOT NULL REFERENCES users(id),
    social_networks varchar(255)
);

CREATE TABLE chats (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_name varchar(255),
    chat_type varchar(255),
    created_at timestamp(6),
    is_private boolean NOT NULL DEFAULT false
);

CREATE TABLE chat_member (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id bigint REFERENCES chats(id),
    user_id bigint REFERENCES users(id),
    joined_at timestamp(6)
);

CREATE TABLE messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_content varchar(255),
    chat_id bigint NOT NULL REFERENCES chats(id),
    type varchar(255),
    sender_id bigint NOT NULL REFERENCES users(id),
    sended_at timestamp(6)
);

CREATE TABLE message_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id bigint REFERENCES messages(id),
    previous_content varchar(255),
    previous_type varchar(255),
    edited_at timestamp(6),
    editor_id bigint REFERENCES users(id)
);

CREATE TABLE message_read_status (
    message_id bigint NOT NULL REFERENCES messages(id),
    user_id bigint NOT NULL REFERENCES users(id),
    read_at timestamp(6),
    PRIMARY KEY (message_id, user_id)
);

CREATE INDEX idx_message_chat_id ON messages(chat_id);
CREATE INDEX idx_message_chat_sended_at ON messages(chat_id, sended_at);
CREATE INDEX idx_message_sender_id ON messages(sender_id);
CREATE INDEX idx_chat_member_chat_id ON chat_member(chat_id);
CREATE INDEX idx_chat_member_user_id ON chat_member(user_id);
